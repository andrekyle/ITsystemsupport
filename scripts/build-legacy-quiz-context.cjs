// Pin only slide definitions that agree across every historical version containing that quiz.
const fs = require("node:fs");
const history = JSON.parse(fs.readFileSync("supabase-export/quiz-definition-history.json", "utf8"));
const crypto = require("node:crypto");
const args = process.argv.slice(2);
const sourceIndex = args.indexOf("--source");
const sourceFile = sourceIndex >= 0 ? args[sourceIndex + 1] : "supabase-export/tsepiso-quiz-source-audit.json";
const tenantIndex = args.indexOf("--tenant");
const tenant = tenantIndex >= 0 ? args[tenantIndex + 1] : undefined;
const builtIndex = args.indexOf("--built");
const builtUnits = new Set(builtIndex >= 0 ? (args[builtIndex + 1] ?? '').split(',').filter(Boolean) : []);
if ((sourceIndex >= 0 && !sourceFile) || (tenantIndex >= 0 && !tenant)) throw new Error("Missing source/tenant argument.");
const sourceAudit = JSON.parse(fs.readFileSync(sourceFile, "utf8"));
const shared = sourceAudit.shared.filter(row => tenant ? row.tenant_id === tenant : true);
if (!tenant && shared.some(row => row.tenant_id)) throw new Error("Supply --tenant for a multi-tenant snapshot.");
const requested = new Set(args.filter((_, index) => ![sourceIndex, tenantIndex, builtIndex].some(option => option >= 0 && (index === option || index === option + 1))));
if (!requested.size) throw new Error("Supply explicitly audited unit IDs.");
const verified = {};
const hashes = {};
const builtSources = {};
for (const [unit, audit] of Object.entries(history)) {
  if (!requested.has(unit)) continue;
  const sources = shared.filter(row => row.key === `itss.lessonedits.${unit}`);
  const source = sources[0];
  if (sources.length !== 1 || shared.some(row => row.key === `itss.unitbuilder.${unit}.shared`) || Object.keys(JSON.parse(source.value).generatedQuizzes ?? {}).length) throw new Error(`Default quiz source has not been verified for ${unit}`);
  if (audit.failures || !audit.versions.length) continue;
  const count = Math.max(...audit.versions.map(version => version.slides.length));
  const slides = {};
  for (let index = 0; index < count; index++) {
    const candidates = audit.versions.map(version => version.slides[index]).filter(slide => slide?.questions.length);
    if (candidates.length && new Set(candidates.map(slide => JSON.stringify(slide))).size === 1) slides[index] = candidates[0];
  }
  if (Object.keys(slides).length) {
    verified[unit] = slides;
    hashes[unit] = crypto.createHash("sha256").update(source.value).digest("hex");
  }
}
for (const unit of builtUnits) {
  const packKey = `itss.unitbuilder.${unit}.shared`;
  const editKey = `itss.lessonedits.${unit}`;
  const packs = shared.filter(row => row.key === packKey);
  const edits = shared.filter(row => row.key === editKey || row.key.startsWith(`${editKey}.built-`));
  if (packs.length !== 1 || new Set(edits.map(row => row.key)).size !== edits.length) throw new Error(`Unverified built source for ${unit}`);
  const pack = JSON.parse(packs[0].value);
  const versions = [pack, ...(pack.history ?? [])];
  const slides = {};
  for (let index = 0; index < (pack.content?.lesson?.length ?? 0); index++) {
    const candidates = versions.map(version => version.content?.lesson?.[index]).filter(slide => slide?.slideQuiz?.length)
      .map(slide => ({ heading: slide.heading, questions: slide.slideQuiz }));
    const archived = edits.flatMap(row => {
      const value = JSON.parse(row.value);
      const questions = value.generatedQuizzes?.[index];
      return questions?.length ? [{ heading: `Slide ${index + 1}`, questions }] : [];
    });
    const all = [...candidates, ...archived];
    const identity = slide => JSON.stringify(slide.questions.map(question => ({ q: question.q, options: question.options, answer: question.answer, imageSvg: question.imageSvg ?? '' })));
    // Require corroboration in at least two saved pack revisions, with no disagreement.
    // Archived generated quizzes are original definitions too. Even one conflicting
    // archived version makes positional relabelling unsafe; never ignore it.
    if (all.length && new Set(all.map(identity)).size === 1 && (candidates.length >= 2 || archived.length)) slides[index] = candidates[0] ?? archived[0];
  }
  if (Object.keys(slides).length) {
    verified[unit] = slides;
    builtSources[unit] = Object.fromEntries([...packs, ...edits].map(row => [row.key, crypto.createHash('sha256').update(row.value).digest('hex')]));
  }
}
fs.writeFileSync("src/data/verifiedLegacyQuizContext.ts", `// Generated by scripts/build-legacy-quiz-context.cjs from read-only Git and saved pack history audits.\n// Contains course definitions only; no learner responses or calculated scores.\nimport type { SlideQuizDefinition } from "../lib/lessonQuizProgress";\nexport const VERIFIED_LEGACY_QUIZ_SOURCE_HASHES: Record<string, string> = ${JSON.stringify(hashes, null, 2)};\nexport const VERIFIED_LEGACY_BUILT_SOURCES: Record<string, Record<string, string>> = ${JSON.stringify(builtSources, null, 2)};\nexport const VERIFIED_LEGACY_QUIZ_CONTEXT: Record<string, Record<number, SlideQuizDefinition>> = ${JSON.stringify(verified, null, 2)};\n`);
