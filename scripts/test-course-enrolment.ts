import assert from "node:assert/strict";
import { createCourse, saveCustomCourse, activeCourse } from "../src/data/courses";
import { isEnrolledInCourse, enrolCourseLearners } from "../src/lib/courseEnrolment";
import { courseScopedKey } from "../src/lib/courseScope";
import { attendanceEvidence } from "../src/lib/attendanceEvidence";
import type { Profile } from "../src/types";
const data = new Map<string,string>();
Object.defineProperty(globalThis,"localStorage",{ configurable:true,value:{get length(){return data.size},key:(i:number)=>[...data.keys()][i]??null,getItem:(k:string)=>data.get(k)??null,setItem:(k:string,v:string)=>data.set(k,v)}});
const learner: Profile = {id:"student-1",cloudUserId:"account-1",name:"Existing student",role:"Learner",createdAt:"2026-11-18"};
const details={title:"New qualification",saqaId:"12345",nqfLevel:5,credits:10,description:"New course",unitCounts:[1],moduleNames:["Module"],unitCodes:[["123"]]};
const modules=[{name:"Module",description:"Module summary",outcomes:["Apply learning"],units:[{us:"123",title:"Unit",nqf:5,credits:10,description:"Unit summary",outcomes:["Apply learning"]}]}];
const first=createCourse(details,modules);saveCustomCourse(first);
const second=createCourse(details,modules);saveCustomCourse(second);
assert.equal(isEnrolledInCourse(learner),true,"Legacy course retains its learners");
assert.equal(courseScopedKey("itss.poe.student-1"),"itss.poe.student-1");
data.set("itss.attendance.2026-11-18",JSON.stringify({rows:{"student-1":{name:"Existing student"}}}));
localStorage.setItem("itss.activeCourse",first.id);
assert.deepEqual(activeCourse().learnerIds,[]);
assert.equal(isEnrolledInCourse(learner),false,"New course starts without inherited students");
assert.equal(attendanceEvidence().size,0,"New course does not inherit signed registers");
assert.equal(courseScopedKey("itss.progress.student-1"),`itss.progress.${first.id}.student-1`);
enrolCourseLearners([learner]);
assert.equal(isEnrolledInCourse(learner),true);
assert.equal(isEnrolledInCourse({...learner,id:"cloud-copy"}),true,"Cloud account resolves enrolment");
data.set(courseScopedKey("itss.attendance.2026-11-18"),JSON.stringify({rows:{"student-1":{name:"New class"}}}));
assert.equal(attendanceEvidence().size,1);
localStorage.setItem("itss.activeCourse",second.id);
assert.equal(isEnrolledInCourse(learner),false,"Enrolling in one course does not enrol in another");
assert.equal(attendanceEvidence().size,0);
localStorage.setItem("itss.activeCourse","it-systems-support");
assert.equal(attendanceEvidence().size,1,"Original register preserved");
assert.ok(data.has(`itss.attendance.${first.id}.2026-11-18`));
console.log("PASS: new-course rosters, explicit enrolment, cloud identity matching, separate attendance/progress keys and preserved legacy records.");
