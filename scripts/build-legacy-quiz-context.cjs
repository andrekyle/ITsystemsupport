// Pin only slide definitions that agree across every historical version containing that quiz.
const fs = require("node:fs");
const history = JSON.parse(fs.readFileSync("supabase-export/quiz-definition-history.json", "utf8"));
const crypto = require("node:crypto");
const sourceAudit = JSON.parse(fs.readFileSync("supabase-export/tsepiso-quiz-source-audit.json", "utf8"));
const requested = new Set(process.argv.slice(2));
if (!requested.size) throw new Error("Supply explicitly audited unit IDs.");
const verified = {};
const hashes = {};
for (const [unit, audit] of Object.entries(history)) {
  if (!requested.has(unit)) continue;
  const source = sourceAudit.shared.find(row => row.key === `itss.lessonedits.${unit}`);
  if (!source || sourceAudit.shared.some(row => row.key === `itss.unitbuilder.${unit}.shared`) || Object.keys(JSON.parse(source.value).generatedQuizzes ?? {}).length) throw new Error(`Default quiz source has not been verified for ${unit}`);
  if (audit.failures || !audit.versions.length) continue;
  const count = Math.max(...audit.versions.map(version => version.slides.length));
  const slides = {};
  for (let index = 0; index < count; index++) {
    const candidates = audit.versions.map(version => version.slides[index]).filter(slide => slide?.questions.length);
    if (candidates.length && new Set(candidates.map(slide => JSON.stringify(slide))).size === 1) slides[index] = candidates[0];
  }
  if (Object.keys(slides).length) {
    verified[unit] = slides;
    hashes[unit] = crypto.createHash("sha256").update(source.value).digest("hex");
  }
}
fs.writeFileSync("src/data/verifiedLegacyQuizContext.ts", `// Generated by scripts/build-legacy-quiz-context.cjs from the read-only Git history audit.\n// Contains course definitions only; no learner responses or calculated scores.\nimport type { SlideQuizDefinition } from "../lib/lessonQuizProgress";\nexport const VERIFIED_LEGACY_QUIZ_SOURCE_HASHES: Record<string, string> = ${JSON.stringify(hashes, null, 2)};\nexport const VERIFIED_LEGACY_QUIZ_CONTEXT: Record<string, Record<number, SlideQuizDefinition>> = ${JSON.stringify(verified, null, 2)};\n`);
console.log(JSON.stringify(Object.fromEntries(Object.entries(verified).map(([unit, slides]) => [unit, Object.keys(slides).length]))));
