/**
 * Generate src/data/figureDefaults.ts from scripts/fetch-figures-report.json
 * and the files present in public/figures/.
 *
 * Usage: node scripts/gen-figure-defaults.mjs
 */
import fs from "node:fs";
import path from "node:path";

const REPORT = path.resolve("scripts", "fetch-figures-report.json");
const FIG_DIR = path.resolve("public", "figures");
const OUT = path.resolve("src", "data", "figureDefaults.ts");

const { results } = JSON.parse(fs.readFileSync(REPORT, "utf8"));
const files = fs.readdirSync(FIG_DIR);

const entries = Object.entries(results)
  .filter(([id, r]) => files.includes(r.file))
  .sort(([a], [b]) => a.localeCompare(b));

const lines = entries.map(([id, r]) => {
  const esc = (s) => String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"');
  return `  "${id}": { src: "/figures/${esc(r.file)}", author: "${esc(r.author)}", license: "${esc(r.license)}", sourceUrl: "${esc(r.sourceUrl)}" },`;
});

const ts = `/**
 * AUTO-GENERATED by scripts/gen-figure-defaults.mjs — do not edit by hand.
 * Default lesson figure images sourced from Wikimedia Commons, served from
 * public/figures/. Staff uploads (via the lesson page) override these.
 */

export interface FigureDefault {
  /** path under public/ */
  src: string;
  /** image author / artist as credited on Wikimedia Commons */
  author: string;
  /** licence short name, e.g. "CC BY-SA 4.0" or "Public domain" */
  license: string;
  /** Wikimedia Commons file page for full attribution */
  sourceUrl: string;
}

export const FIGURE_DEFAULTS: Record<string, FigureDefault> = {
${lines.join("\n")}
};
`;

fs.writeFileSync(OUT, ts);
console.log(`Wrote ${OUT} with ${entries.length} entries.`);
